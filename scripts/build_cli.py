#!/usr/bin/env python3
"""Build a portable nec2++ command-line executable from a necpp source tree.

The engine is configured as the pynec-accel Python wheel configures it: the
OpenMP matrix fill, and the LU through LAPACKE (zgetrf/zgetrs) into OpenBLAS.

One executable carries the engine twice: once compiled for the x86-64
baseline (SSE2) and once for x86-64-v3 (AVX2 + FMA). A small dispatcher picks
one at start-up from cpuid. Set NECPP_ENGINE=baseline to force the baseline
copy (NECPP_ENGINE=avx2 forces the other, refusing on a CPU without it), and
NECPP_ENGINE_VERBOSE=1 to have it say on stderr which copy ran.

  Linux (gcc):    fully static; OpenBLAS built here from the release tarball
                  (DYNAMIC_ARCH, OpenMP threading).
  Windows (MSVC): run from a VS developer prompt; OpenBLAS is the
                  scipy-openblas32 wheel's DLL (as the pynec-accel Windows
                  wheels use), which ships beside the .exe with vcomp140.dll.

Usage:
  python3 scripts/build_cli.py --variant accel|reuse --src <necpp checkout>
      [--out DIR] [--work DIR] [--openblas-prefix DIR] [--jobs N]

  --variant reuse applies patch 0002 (fill-pair reuse ON by default; the
  environment variable PYNEC_FILL_REUSE=0 still turns it off). Both variants
  get patch 0001 (nec2++ -n skips the wire-intersection check). See
  BUILD-CLI.md.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import hashlib
import os
import platform
import re
import shutil
import subprocess
import sys
import tarfile
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent

OPENBLAS_VERSION = os.environ.get("OPENBLAS_VERSION", "0.3.34")
# The GitHub release page's asset digest for OpenBLAS-0.3.34.tar.gz.
OPENBLAS_SHA256 = os.environ.get(
    "OPENBLAS_SHA256", "cd7e129868320cc2d033afa920e31202dfe0b8066a5b66661900ccc0f197dfed"
)
# DYNAMIC_ARCH=1: kernels for the running CPU picked at load time; TARGET is
# the floor for the common code (PRESCOTT, as scipy-openblas). USE_OPENMP=1 so
# OpenBLAS and the fill share one libgomp. NUM_THREADS=64: the default is the
# BUILD machine's core count, which would cap a CI-built library at 4 threads.
# C_LAPACK=1/NOFORTRAN=1: no Fortran runtime to link; zgetrf/zgetrs are
# OpenBLAS's own (interface/lapack), not the reference LAPACK, either way.
OPENBLAS_FLAGS = [
    "DYNAMIC_ARCH=1", "TARGET=PRESCOTT", "USE_OPENMP=1", "NO_SHARED=1",
    "NUM_THREADS=64", "NOFORTRAN=1", "C_LAPACK=1", "BUILD_TESTING=0", "NO_AFFINITY=1",
]

# The engine sources nec2++ needs. libNEC.cpp (the C API) is not used by the
# command line and is left out: its extern "C" functions cannot be duplicated.
SOURCES = [
    "c_evlcom", "c_geometry", "c_ggrid", "c_plot_card", "matrix_algebra", "misc",
    "nec_context", "nec_exception", "nec_ground", "nec_output",
    "nec_radiation_pattern", "nec_structure_currents", "electromag",
    "nec_results", "nec2cpp", "XGetopt",
]

# Sources whose "avx2" copy is still compiled at the baseline. A copy's
# dynamic initialisers run at start-up, BEFORE the dispatcher has chosen, so
# the avx2 copy must have none: electromag.cpp's one
# (em::constants::permeability = four_pi() * 1.0e-7) would be a VEX vmulsd
# on a CPU without AVX. It is not hot. check_no_initialisers() enforces the
# rule for every other avx2 object.
BASELINE_ONLY = {"electromag"}

# Every system header the engine includes, so each is first seen OUTSIDE the
# engine namespace (their include guards then keep them out of it).
PRELUDE = r"""/* generated by scripts/build_cli.py */
#include <algorithm>
#include <atomic>
#include <cctype>
#include <chrono>
#include <cmath>
#include <complex>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <map>
#include <memory>
#include <ostream>
#include <sstream>
#include <string>
#include <tuple>
#include <vector>
#include <ctype.h>
#include <signal.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#ifndef _WIN32
#include <sys/times.h>
#include <unistd.h>
#endif
#ifdef _OPENMP
#include <omp.h>
#endif
#define lapack_complex_double std::complex<double>
#define lapack_complex_float  std::complex<float>
#include <lapacke.h>
"""

WRAPPER = """/* generated by scripts/build_cli.py: the {ns} copy of {src}.cpp */
#include "nec_cli_prelude.h"
#define NECPP_NS {ns}
{pre}namespace {ns} {{
#include "../src/{src}.cpp"
}}
"""

DISPATCH = r"""/* generated by scripts/build_cli.py: pick the engine copy at start-up */
#include <cstdio>
#include <cstdlib>
#include <cstring>
#if defined(_MSC_VER)
#include <intrin.h>
#include <immintrin.h>
#endif

#if defined(NECPP_OPENBLAS_STATIC_OPENMP)
#include <omp.h>
extern "C" void openblas_set_num_threads(int);
#endif

namespace nec_base { int nec_cli_entry(int argc, char **argv); }
namespace nec_avx2 { int nec_cli_entry(int argc, char **argv); }

/* x86-64-v3: AVX, AVX2, FMA, BMI1, BMI2, LZCNT, MOVBE, F16C, and the OS
   saving the YMM state. */
static bool cpu_has_v3() {
#if defined(_MSC_VER)
  int r[4];
  __cpuid(r, 0);
  if (r[0] < 7) return false;
  __cpuid(r, 1);
  const unsigned c1 = (unsigned)r[2];
  const bool fma = (c1 >> 12) & 1, movbe = (c1 >> 22) & 1, osxsave = (c1 >> 27) & 1,
             avx = (c1 >> 28) & 1, f16c = (c1 >> 29) & 1;
  if (!(fma && movbe && osxsave && avx && f16c)) return false;
  if ((_xgetbv(0) & 6) != 6) return false;
  __cpuidex(r, 7, 0);
  const unsigned b7 = (unsigned)r[1];
  const bool bmi1 = (b7 >> 3) & 1, avx2 = (b7 >> 5) & 1, bmi2 = (b7 >> 8) & 1;
  __cpuid(r, 0x80000001);
  const bool lzcnt = ((unsigned)r[2] >> 5) & 1;
  return avx2 && bmi1 && bmi2 && lzcnt;
#else
  __builtin_cpu_init();
  return __builtin_cpu_supports("x86-64-v3");
#endif
}

int main(int argc, char **argv) {
#if defined(NECPP_OPENBLAS_STATIC_OPENMP)
  /* In a static link OpenBLAS's constructor runs before libgomp's has read
     OMP_NUM_THREADS, so OpenBLAS caps itself at one thread (the LU then runs
     serially). Set its thread count explicitly, once libgomp is up:
     OPENBLAS_NUM_THREADS if given, else OpenMP's own count. */
  {
    const char *e = std::getenv("OPENBLAS_NUM_THREADS");
    int n = (e && std::atoi(e) > 0) ? std::atoi(e) : omp_get_max_threads();
    openblas_set_num_threads(n);
  }
#endif
  const bool v3 = cpu_has_v3();
  const char *force = std::getenv("NECPP_ENGINE");
  bool use_avx2 = v3;
  if (force && *force && std::strcmp(force, "auto") != 0) {
    if (std::strcmp(force, "baseline") == 0) {
      use_avx2 = false;
    } else if (std::strcmp(force, "avx2") == 0) {
      if (!v3) {
        std::fprintf(stderr, "nec2++: NECPP_ENGINE=avx2 but this CPU lacks x86-64-v3 (AVX2/FMA)\n");
        return 2;
      }
      use_avx2 = true;
    } else {
      std::fprintf(stderr, "nec2++: NECPP_ENGINE must be auto, baseline or avx2 (got '%s')\n", force);
      return 2;
    }
  }
  bool say = std::getenv("NECPP_ENGINE_VERBOSE") != nullptr;
  for (int i = 1; i < argc; i++)
    if (std::strcmp(argv[i], "-v") == 0) say = true;
  if (say)
    std::fprintf(stderr, "nec2++ engine: %s (cpu x86-64-v3: %s%s)\n",
                 use_avx2 ? "avx2" : "baseline", v3 ? "yes" : "no",
                 (force && *force) ? ", NECPP_ENGINE set" : "");
  return use_avx2 ? nec_avx2::nec_cli_entry(argc, argv) : nec_base::nec_cli_entry(argc, argv);
}
"""


def run(cmd: list[str], **kw) -> None:
    print("+", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, **kw)


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def build_openblas(work: Path, prefix: Path, jobs: int, cc: str) -> None:
    if (prefix / "lib" / "libopenblas.a").exists():
        print(f"OpenBLAS: reusing {prefix}")
        return
    tb = work / f"OpenBLAS-{OPENBLAS_VERSION}.tar.gz"
    if not tb.exists():
        url = (f"https://github.com/OpenMathLib/OpenBLAS/releases/download/"
               f"v{OPENBLAS_VERSION}/OpenBLAS-{OPENBLAS_VERSION}.tar.gz")
        print(f"fetching {url}")
        urllib.request.urlretrieve(url, tb.with_suffix(".part"))
        tb.with_suffix(".part").rename(tb)
    got = sha256(tb)
    if got != OPENBLAS_SHA256:
        sys.exit(f"OpenBLAS tarball sha256 {got} != expected {OPENBLAS_SHA256}")
    print(f"OpenBLAS tarball sha256 OK: {got}")
    srcdir = work / f"OpenBLAS-{OPENBLAS_VERSION}"
    shutil.rmtree(srcdir, ignore_errors=True)
    with tarfile.open(tb) as t:
        t.extractall(work, filter="tar") if hasattr(tarfile, "data_filter") else t.extractall(work)
    flags = OPENBLAS_FLAGS + [f"CC={cc}", f"HOSTCC={cc}"]
    with open(work / "openblas-build.log", "w") as log:
        subprocess.run(["make", f"-j{jobs}", *flags, "libs", "netlib"], cwd=srcdir,
                       stdout=log, stderr=subprocess.STDOUT, check=True)
        subprocess.run(["make", *flags, f"PREFIX={prefix}", "install"], cwd=srcdir,
                       stdout=log, stderr=subprocess.STDOUT, check=True)


def check_no_initialisers(objs: list[Path], msvc: bool) -> None:
    """An avx2-compiled object must not run code at start-up (see BASELINE_ONLY)."""
    bad = []
    for o in objs:
        if msvc:
            hdr = subprocess.run(["dumpbin", "/nologo", "/headers", str(o)], capture_output=True,
                                 text=True, check=True).stdout
            if ".CRT$X" in hdr:  # .CRT$XCU (dynamic init), .CRT$XDU (thread_local init)
                bad.append(o.name)
        else:
            hdr = subprocess.run(["objdump", "-h", str(o)], capture_output=True, text=True, check=True).stdout
            if re.search(r"\s\.(init_array|ctors)\b", hdr):
                bad.append(o.name)
    if bad:
        sys.exit(f"avx2 objects with start-up initialisers (would run before dispatch): {bad}; "
                 "add their sources to BASELINE_ONLY")
    print(f"start-up initialisers: none in the {len(objs)} avx2 objects")


def patch_tree(tree: Path, variant: str) -> None:
    # 0003 only lets math_util.h name the engine namespace; with NECPP_NS
    # undefined it is the original code.
    patches = ["0001-cli-n-skips-intersection-check.patch", "0003-math-util-engine-namespace.patch"]
    if variant == "reuse":
        if "const int FILL_REUSE_DEFAULT = 0;" not in (tree / "src/nec_context.cpp").read_text():
            sys.exit("this tree has no fill-pair reuse (FILL_REUSE_DEFAULT): wrong commit for --variant reuse")
        patches.append("0002-fill-reuse-default-on.patch")
    for p in patches:
        run(["patch", "-d", str(tree), "-p1", "--forward", "--binary", "-i", str(HERE / "patches" / p)])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--variant", choices=["accel", "reuse"], required=True)
    ap.add_argument("--src", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=Path("out"))
    ap.add_argument("--work", type=Path, default=Path("build-cli"))
    ap.add_argument("--openblas-prefix", type=Path, default=None)
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    a = ap.parse_args()

    src = a.src.resolve()
    if not (src / "src/nec_context.cpp").exists():
        sys.exit("--src must be a necpp tree")
    a.out.mkdir(parents=True, exist_ok=True)
    a.work.mkdir(parents=True, exist_ok=True)
    out, work = a.out.resolve(), a.work.resolve()
    msvc = platform.system() == "Windows"
    osname = "windows" if msvc else "linux"

    sha = subprocess.run(["git", "-C", str(src), "rev-parse", "--short=7", "HEAD"],
                         capture_output=True, text=True).stdout.strip() or "unknown"
    date = subprocess.run(["git", "-C", str(src), "log", "-1", "--format=%cs"],
                          capture_output=True, text=True).stdout.strip() or "unknown"

    # --- OpenBLAS -----------------------------------------------------------
    defines = ["LAPACK=1", "LAPACKE=1", "NDEBUG"]
    if msvc:
        import scipy_openblas32 as ob  # pip install scipy-openblas32==<pinned>

        ob_inc, ob_lib, ob_name = Path(ob.get_include_dir()), Path(ob.get_lib_dir()), ob.get_library()
        # scipy-openblas prefixes every symbol (see PyNEC/setup.py).
        defines += ["LAPACKE_zgetrf_work=scipy_LAPACKE_zgetrf_work",
                    "LAPACKE_zgetrs_work=scipy_LAPACKE_zgetrs_work"]
    else:
        cc = os.environ.get("CC", "gcc")
        prefix = (a.openblas_prefix or work / f"openblas-{OPENBLAS_VERSION}").resolve()
        build_openblas(work, prefix, a.jobs, cc)
        ob_inc, ob_lib = prefix / "include", prefix / "lib"

    # --- patched copy of the sources ----------------------------------------
    tree = work / f"tree-{a.variant}-{sha}"
    shutil.rmtree(tree, ignore_errors=True)
    tree.mkdir(parents=True)
    shutil.copytree(src / "src", tree / "src")
    shutil.copytree(src / "win32", tree / "win32")
    patch_tree(tree, a.variant)
    m = re.search(r"AC_INIT\(\[necpp\],\[([^\]]+)\]\)", (src / "configure.ac").read_text())
    version = m.group(1) if m else "unknown"
    # What configure writes; the engine reads only VERSION/BUILD_DATE (Eigen
    # stays off, as in the wheel). Windows builds read win32/nec2++/config.h,
    # and build_version/nec_build_date below override both.
    (tree / "config.h").write_text(
        f'#define PACKAGE "necpp"\n#define VERSION "{version}"\n#define BUILD_DATE "{date}"\n')
    fat = tree / "fat"
    fat.mkdir()
    (fat / "nec_cli_prelude.h").write_text(PRELUDE)
    (fat / "dispatch.cpp").write_text(DISPATCH)
    units: list[tuple[Path, str]] = [(fat / "dispatch.cpp", "base")]
    for arch, ns in (("base", "nec_base"), ("avx2", "nec_avx2")):
        for s in SOURCES:
            pre = "#define main nec_cli_entry\n" if s == "nec2cpp" else ""
            w = fat / f"{ns}_{s}.cpp"
            w.write_text(WRAPPER.format(ns=ns, src=s, pre=pre))
            units.append((w, "base" if s in BASELINE_ONLY else arch))

    label = f"{version} {a.variant} {sha}"
    name = f"nec2++-{'accel-reuse' if a.variant == 'reuse' else 'accel'}-{sha}-{osname}-x86_64"
    objdir = tree / "obj"
    objdir.mkdir()

    if msvc:
        common = ["cl", "/nologo", "/c", "/O2", "/MT", "/EHsc", "/bigobj", "/openmp",
                  "/FImsvc_compat.h", "/I", str(HERE / "msvc"), "/I", str(tree), "/I", str(tree / "src"),
                  "/I", str(fat), "/I", str(ob_inc), *[f"/D{d}" for d in defines],
                  f'/Dbuild_version="{label}"', f'/Dnec_build_date="{date}"']
        archflag = {"base": [], "avx2": ["/arch:AVX2"]}

        def compile_one(u: tuple[Path, str]) -> Path:
            o = objdir / (u[0].stem + ".obj")
            run([*common, *archflag[u[1]], str(u[0]), f"/Fo{o}"])
            return o
    else:
        cxx = os.environ.get("CXX", "g++")
        # pynec-accel 1.7.6's _PyNEC.so records (DW_AT_producer):
        #   -mtune=generic -march=x86-64 -O3 -fno-strict-overflow -fPIC -fopenmp
        common = [cxx, "-c", "-O3", "-fno-strict-overflow", "-mtune=generic", "-fopenmp",
                  "-I", str(tree), "-I", str(tree / "src"), "-I", str(fat), "-I", str(ob_inc),
                  *[f"-D{d}" for d in defines],
                  f'-Dbuild_version="{label}"', f'-Dnec_build_date="{date}"']
        archflag = {"base": ["-march=x86-64"], "avx2": ["-march=x86-64-v3"]}
        common.append("-DNECPP_OPENBLAS_STATIC_OPENMP=1")

        def compile_one(u: tuple[Path, str]) -> Path:
            o = objdir / (u[0].stem + ".o")
            run([*common, *archflag[u[1]], str(u[0]), "-o", str(o)])
            return o

    with concurrent.futures.ThreadPoolExecutor(a.jobs) as ex:
        objs = list(ex.map(compile_one, units))

    check_no_initialisers([o for o, u in zip(objs, units) if u[1] == "avx2"], msvc)

    if msvc:
        exe = out / f"{name}.exe"
        run(["cl", "/nologo", "/MT", "/openmp", *map(str, objs), f"/Fe{exe}",
             "/link", f"/LIBPATH:{ob_lib}", f"{ob_name}.lib"])
        # Runtime DLLs that ship beside the .exe.
        dll = next(Path(ob.get_lib_dir()).parent.rglob(f"{ob_name}*.dll"), None) or next(
            Path(ob.__file__).parent.rglob("*.dll"))
        shutil.copy2(dll, out / dll.name)
        print(f"bundled {dll.name}")
        # The wheel's licence file (OpenBLAS + the runtimes inside its DLL).
        import importlib.metadata as md

        dist = md.distribution("scipy-openblas32")
        lic = [f for f in (dist.files or []) if re.search(r"LICEN[CS]E", f.name, re.I)]
        if lic:
            (out / "scipy-openblas32-LICENSE.txt").write_text(
                "\n\n".join(Path(dist.locate_file(f)).read_text(errors="replace") for f in lic))
        else:
            sys.exit("scipy-openblas32 ships no licence file to bundle")
    else:
        exe = out / name
        run([cxx, "-static", "-fopenmp", "-o", str(exe), *map(str, objs),
             str(ob_lib / "libopenblas.a"), "-lm"])
        run(["strip", str(exe)])
    print(f"built {exe}  sha256 {sha256(exe)}")


if __name__ == "__main__":
    main()
